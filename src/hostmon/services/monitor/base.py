"""
1. **HTTP(S)**: URL, метод (GET/HEAD), ожидаемый статус (по умолчанию 2xx–3xx), необязательное ключевое слово в теле ответа, необязательные заголовки (например, Authorization), таймаут (по умолчанию 10 с). Редиректы проходятся. Время ответа записывается.
2. **TCP-порт**: host:port, успех — если соединение установилось за время таймаута.
3. **Ping**: ICMP через `github.com/prometheus-community/pro-bing` в unprivileged-режиме. Если ICMP недоступен, переходи на TCP-проверку порта 80/443 и пиши об этом в лог.
4. **SSL**: хост:443. Проверяй срок действия сертификата и предупреждай за N дней до истечения (по умолчанию 14, 7, 1 — по одному уведомлению на каждый порог). Для HTTPS-мониторов SSL проверяется автоматически, отдельный монитор не нужен.

"""


from typing import Protocol


class BaseMonitor(Protocol):
    @classmethod
    def healthcheck(cls, url: str) -> bool:
        return False
